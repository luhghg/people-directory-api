#!/bin/sh

# Перехватываем любые ошибки: если какая-то команда упадет, скрипт остановится
set -e

print_msg() {
    echo "========================================="
    echo "$1"
    echo "========================================="
}

print_msg "⏳ Ожидание запуска базы данных..."

# Цикл, который проверяет доступность порта базы данных (db — это имя сервиса из compose)
# Мы используем встроенную в python команду, чтобы не ставить лишние утилиты типа netcat
until python -c "import socket; s = socket.socket(); s.connect(('db', 5432))" 2>/dev/null; do
  echo "База данных еще не готова, ждем 1 секунду..."
  sleep 1
done

print_msg "⏳ Ожидание запуска базы данных..."

# 1. Применяем миграции Alembic
alembic upgrade head

print_msg "🚀 Миграции применены успешно! Запуск приложения..."

# 2. Запускаем само приложение (вместо main.py укажи свой стартовый файл или команду uvicorn/gunicorn)
exec python main.py
